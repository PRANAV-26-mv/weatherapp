export function translate(key: string, langCode: string = 'en'): string {
  const langDict = DICTIONARY[langCode] || DICTIONARY['en'];
  return langDict[key] || DICTIONARY['en'][key] || key;
}

export function translateWeatherCondition(conditionText: string, langCode: string = 'en'): string {
  if (langCode === 'en') return conditionText;
  const langDict = WEATHER_CONDITION_TRANSLATIONS[langCode];
  if (!langDict) return conditionText;

  // Try exact match or case-insensitive lookup
  for (const [key, value] of Object.entries(langDict)) {
    if (key.toLowerCase() === conditionText.toLowerCase() || conditionText.toLowerCase().includes(key.toLowerCase())) {
      return value;
    }
  }

  return conditionText;
}

